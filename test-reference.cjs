const assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto'),vm=require('node:vm');
const R=require('./docs/reference-data.js'),A=require('./docs/reference-audit.js');
const H=require('./docs/homework-data.js'),UI=require('./docs/reference.js'),X=require('./docs/exam-data.js'),E=require('./docs/engine.js');
assert.equal(R.questions.length,26);assert.equal(A.entries.length,26);
assert.deepEqual(R.questions.map(q=>q.number),Array.from({length:26},(_,i)=>i+1));
const tables=R.questions.flatMap(q=>q.blocks.filter(b=>b.type==='table'));
