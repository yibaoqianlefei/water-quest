const assert=require('node:assert/strict');
const root=require('node:path').join(__dirname,'docs')+require('node:path').sep;
const C=require(root+'coach.js'),E=require(root+'engine.js'),D=require(root+'bank.js');
const now=Date.parse('2026-11-06T12:00:00+08:00');
assert.equal(C.examTime(C.DEFAULT_EXAM),Date.parse('2026-11-11T04:20:00Z'));
assert.throws(()=>C.examTime('2026-02-30T12:00'));
assert.deepEqual(C.countdown(C.fresh(now),now),{arrived:false,days:5,hours:0,minutes:20});
assert.equal(C.countdown(C.fresh(now),Date.parse('2026-11-11T04:20:00Z')).arrived,true);
assert.equal(C.dayKey(Date.parse('2026-11-06T16:00:00Z')),'2026-11-07');
const s=C.fresh(now),ids=D.questions.slice(0,12).map(q=>q.id);
C.record(s,ids[0],true,now);assert.equal(s.hearts,1);
C.record(s,ids[0],true,now);assert.equal(s.hearts,1);assert.equal(s.day.streak,1);
C.record(s,ids[1],true,now);C.record(s,ids[2],true,now);assert.equal(s.hearts,5);
C.record(s,ids[3],false,now);assert.equal(s.hearts,4);assert.equal(s.day.streak,0);assert.ok(C.needsReview(s,ids[3]));
assert.throws(()=>C.review(s,ids[3],'记住'));assert.ok(C.needsReview(s,ids[3]));
C.review(s,ids[3],'认真看清题干限定条件。');assert.equal(C.needsReview(s,ids[3]),false);
C.record(s,ids[3],true,now);assert.equal(s.hearts,6);assert.equal(s.debt[ids[3]],undefined);
for(const id of ids.slice(4))C.record(s,id,true,now);assert.equal(s.hearts,17);assert.equal(s.day.goalBonus,true);
C.record(s,ids[11],true,now);assert.equal(s.hearts,17);
C.record(s,ids[3],false,now);C.review(s,ids[3],'再看清题干中的限定条件。');C.record(s,ids[3],true,now);assert.equal(s.hearts,16,'No repeated repair reward on the same day');
const reward=C.redeem(s,'rest',now);assert.equal(reward.cost,10);assert.equal(s.hearts,6);assert.throws(()=>C.redeem(s,'wish',now));assert.equal(s.hearts,6);
C.today(s,now+86400000);assert.equal(s.day.seen.length,0);assert.equal(s.hearts,6);assert.equal(s.day.streak,0);
const zero=C.fresh(now);C.record(zero,ids[0],false,now);assert.equal(zero.hearts,0);
const saved=C.validate(JSON.parse(JSON.stringify(s)),D.questions,now+86400000);assert.equal(saved.hearts,6);assert.equal(saved.rewards[0].id,'rest');
assert.equal(C.validate(undefined,D.questions,now).hearts,0);assert.throws(()=>C.validate({...s,hearts:-1},D.questions,now));
const bad=C.fresh(now);bad.debt.invalid={reviewed:false,note:'',date:C.dayKey(now)};assert.throws(()=>C.validate(bad,D.questions,now));
const state=E.fresh(),q=D.questions[0];E.record(state,q,(q.answer+1)%q.options.length);assert.ok(state.wrong.includes(q.id));assert.ok(C.needsReview(state.sweet,q.id));
C.review(state.sweet,q.id,'这里必须注意题目问的是复合管。');
const restored=E.validateState(JSON.parse(JSON.stringify(state)),D.questions);assert.equal(restored.sweet.debt[q.id].note,'这里必须注意题目问的是复合管。');
E.record(restored,q,q.answer);assert.ok(!restored.wrong.includes(q.id));assert.equal(restored.sweet.debt[q.id],undefined);
const legacy=JSON.parse(JSON.stringify(state));delete legacy.sweet;assert.ok(E.validateState(legacy,D.questions).sweet.debt[q.id]);
assert.equal(C.plan(C.fresh(now),now)[0].today,true);assert.equal(C.plan(C.fresh(now),now)[5].date,'2026-11-11');
console.log('PASS: exam timezone, date validation, unique daily credits, streak bonus, penalties, mandatory review, repair rewards, redemption, day rollover, backup recovery and legacy import.');
